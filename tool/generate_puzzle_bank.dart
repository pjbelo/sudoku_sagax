// ============================================================
// Sudoku Sagax — puzzle bank generator (run on a computer, not in the app)
// ============================================================
//
// Writes lib/game/puzzle_bank.dart: puzzles for the levels that need more
// than singles (6 to 9), each graded by the logic coach so that it needs
// the level's technique and nothing harder. Finding such puzzles takes from
// a fraction of a second (level 6) to many seconds (level 9, X-Wing), too
// slow for the app; the app shuffles these instead (see generatePuzzle).
//
//   dart run tool/generate_puzzle_bank.dart [puzzles per level]
//
// Once the app ships, keep the bank as it is: the daily puzzle (B5) picks
// from it by date, so changing it would change that day's puzzle.

import 'dart:io';
import 'dart:math';

import 'package:sudoku_sagax/game/logic_coach.dart';
import 'package:sudoku_sagax/game/sudoku_generator.dart';

void main(List<String> args) {
  final perLevel = args.isEmpty ? 100 : int.parse(args.first);
  final rng = Random(2026);
  final bank = <int, List<String>>{};

  for (final spec in sudokuLevels) {
    if (spec.technique == SudokuTechnique.singles) continue;
    final found = <String>{}; // a set, so no puzzle comes twice
    final clock = Stopwatch()..start();
    while (found.length < perLevel) {
      final puzzle = _search(spec, rng);
      if (puzzle == null) continue;
      found.add(puzzle);
      stdout.write(
        '\rlevel ${spec.level}: ${found.length}/$perLevel '
        '(${clock.elapsed.inSeconds} s)',
      );
    }
    stdout.writeln();
    bank[spec.level] = found.toList();
  }

  File('lib/game/puzzle_bank.dart').writeAsStringSync(_dartFile(bank));
  stdout.writeln('Wrote lib/game/puzzle_bank.dart');
}

/// One try at a puzzle for [spec]: dig a random grid down to the clue
/// target, keeping it solvable by logic with nothing harder than the level
/// allows; then swap clues (one out, another in) while the puzzle gets no
/// easier, until it needs the level's technique. Null when it doesn't.
String? _search(SudokuLevel spec, Random rng) {
  final (simplest, hardestAllowed) = techniqueRange(spec.technique);
  CoachTechnique? grade(List<int> givens) =>
      hardestTechnique(givens, limit: hardestAllowed);

  final solution = randomSolvedGrid(rng);
  final givens = List.of(solution);
  var clues = 81;
  for (final i in List.generate(81, (i) => i)..shuffle(rng)) {
    if (clues <= spec.clues) break;
    givens[i] = 0;
    if (grade(givens) != null) {
      clues--;
    } else {
      givens[i] = solution[i];
    }
  }
  if (clues != spec.clues) return null;

  var current = grade(givens)!;
  for (int swap = 0; swap < 800; swap++) {
    if (current.index >= simplest.index) break;
    final filled = [
      for (int i = 0; i < 81; i++)
        if (givens[i] != 0) i,
    ];
    final empty = [
      for (int i = 0; i < 81; i++)
        if (givens[i] == 0) i,
    ];
    final out = filled[rng.nextInt(filled.length)];
    final into = empty[rng.nextInt(empty.length)];
    givens[out] = 0;
    givens[into] = solution[into];
    final next = grade(givens);
    if (next != null && next.index >= current.index) {
      current = next;
    } else {
      givens[out] = solution[out]; // undo the swap
      givens[into] = 0;
    }
  }
  if (!meetsLevel(spec.technique, hardestTechnique(givens))) return null;
  return givens.join();
}

String _dartFile(Map<int, List<String>> bank) {
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_puzzle_bank.dart. Do not edit.')
    ..writeln('//')
    ..writeln('// Puzzles for levels 6 to 9, 81 digits each (0 = empty), row by')
    ..writeln("// row. Each needs its level's technique and nothing harder; the")
    ..writeln('// app shuffles them (generatePuzzle). Keep the bank as it is once')
    ..writeln('// shipped: the daily puzzle picks from it by date.')
    ..writeln()
    ..writeln('const puzzleBank = <int, List<String>>{');
  for (final MapEntry(key: level, value: puzzles) in bank.entries) {
    out.writeln('  $level: [');
    for (final puzzle in puzzles) {
      out.writeln("    '$puzzle',");
    }
    out.writeln('  ],');
  }
  out.writeln('};');
  return out.toString();
}
